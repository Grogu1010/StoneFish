const assert=require('node:assert/strict');
require('./armx_deferred_causal.js');
const book={pendingTrajectories:[]},map=new Map(),available=new Set(['quiet']),chosen=new Set(['quiet']);
armxCausalQueueTrajectory(book,map,available,chosen,100,10,40);
const event=book.pendingTrajectories[0];assert.equal(event.expectedAfter,40);
armxCausalResolveTrajectories(book,12,130);
const row=map.get('quiet');
assert.equal(row.shortTreatedImpact,90/ARMX_PREVIEW.effectScale,'short credit includes chosen outcome minus frozen alternative expectation');
assert.equal(row.shortTreatedWeight,1);
armxCausalResolveTrajectories(book,14,160);
assert.equal(row.longTreatedImpact,120/ARMX_PREVIEW.effectScale);
assert.equal(book.pendingTrajectories.length,0);
const controls={pendingTrajectories:[]},controlMap=new Map();
armxCausalQueueTrajectory(controls,controlMap,available,new Set(),100,10,40);
armxCausalResolveTrajectories(controls,12,130);
assert.equal(controlMap.get('quiet').shortControlImpact,row.shortTreatedImpact,'treatment and control share the same outcome definition');
const contaminated={pendingTrajectories:[]},contaminationMap=new Map();
armxCausalQueueTrajectory(contaminated,contaminationMap,available,chosen,100,10,40);
armxCausalResolveTrajectories(contaminated,12,1000);
assert.ok(contaminationMap.get('quiet').shortTreatedWeight<1,'intervening shock still reduces attribution');
console.log('ARMX_EXPECTED_TRAJECTORY passed: frozen counterfactual baseline, consistent horizons/treatment/control and contamination discount');
